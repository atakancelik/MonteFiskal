<?php
/**
 * Fiscal invoice block in e-mails, on the order-received page and in My Account.
 *
 * Override by copying to yourtheme/woocommerce/montefiskal/fiscal-block.php.
 *
 * @var \MonteFiskal\Outbox\StoredRequest $doc
 * @var \WC_Order $order
 * @var bool $plain_text
 * @var string $context email|page
 * @var string $qr SVG markup (page) or PNG data URI (email)
 * @var string $print_url
 * @var bool $test_mode
 *
 * @package MonteFiskal\WooCommerce
 */

declare(strict_types=1);

use MonteFiskal\WooCommerce\Frontend\CustomerOutput;

defined('ABSPATH') || exit;

$fic = $doc->result ?? __('not yet registered', 'montefiskal-woocommerce');

if ($plain_text) {
    echo "\n" . esc_html__('Fiscal invoice', 'montefiskal-woocommerce') . "\n";
    echo esc_html__('Number', 'montefiskal-woocommerce') . ': ' . esc_html((string) $doc->invoiceNumber) . "\n";
    echo 'IKOF: ' . esc_html((string) $doc->iic) . "\n";
    echo 'JIKR: ' . esc_html($fic) . "\n";
    echo esc_html__('Verify', 'montefiskal-woocommerce') . ': ' . esc_url_raw((string) $doc->verificationUrl) . "\n";
    echo esc_html__('Printable invoice', 'montefiskal-woocommerce') . ': ' . esc_url_raw($print_url) . "\n";
    if ($test_mode) {
        echo esc_html__('TEST MODE: this invoice is not legally valid.', 'montefiskal-woocommerce') . "\n";
    }
    return;
}
?>
<section class="montefiskal-fiscal-block" style="margin:16px 0;padding:12px;border:1px solid #ddd;">
    <h2 style="margin-top:0;"><?php esc_html_e('Fiscal invoice', 'montefiskal-woocommerce'); ?></h2>
    <?php if ($test_mode) : ?>
        <p style="color:#b00;font-weight:700;"><?php esc_html_e('TEST MODE: this invoice is not legally valid.', 'montefiskal-woocommerce'); ?></p>
    <?php endif; ?>
    <table style="width:100%;border:0;" role="presentation">
        <tr>
            <td style="vertical-align:top;">
                <p>
                    <?php esc_html_e('Number', 'montefiskal-woocommerce'); ?>: <strong><?php echo esc_html((string) $doc->invoiceNumber); ?></strong><br>
                    IKOF: <code><?php echo esc_html((string) $doc->iic); ?></code><br>
                    JIKR: <code><?php echo esc_html($fic); ?></code><br>
                    <?php echo esc_html(CustomerOutput::stateText($doc)); ?>
                </p>
                <p>
                    <a href="<?php echo esc_url((string) $doc->verificationUrl); ?>"><?php esc_html_e('Verify this invoice with the tax administration', 'montefiskal-woocommerce'); ?></a><br>
                    <a href="<?php echo esc_url($print_url); ?>"><?php esc_html_e('Printable invoice', 'montefiskal-woocommerce'); ?></a>
                </p>
            </td>
            <td style="vertical-align:top;width:30mm;">
                <?php if ($context === 'email' && $qr !== '') : ?>
                    <img src="<?php echo esc_attr($qr); ?>" width="96" height="96" style="width:25mm;height:25mm;" alt="<?php esc_attr_e('QR code for verification', 'montefiskal-woocommerce'); ?>">
                <?php elseif ($qr !== '') : ?>
                    <?php echo $qr; // phpcs:ignore WordPress.Security.EscapeOutput -- SVG generated by the core QR encoder from the verification URL ?>
                <?php endif; ?>
            </td>
        </tr>
    </table>
</section>
