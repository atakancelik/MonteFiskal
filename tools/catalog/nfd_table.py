"""Writes src/php/montefiskal-core/src/Text/nfd-ascii.php: for every BMP code point above 126 whose NFD
decomposition differs from itself, the ASCII characters of that decomposition. Run with: python3 -I nfd_table.py"""
import pathlib
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[2]
lines = []
for cp in range(0x7F, 0x10000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    d = unicodedata.normalize("NFD", c)
    b = "".join(x for x in d if ord(x) <= 126)
    if b and d != c:
        lines.append("    0x%04X => '%s'," % (cp, b.replace("\\", "\\\\").replace("'", "\\'")))
out = (
    "<?php\n\ndeclare(strict_types=1);\n\n"
    "// Generated by tools/catalog/nfd_table.py from the Unicode NFD decomposition: code point => ASCII part of its\n"
    "// decomposition. Used by TextRules::transliterate so that PHP needs no ext-intl and matches .NET's FormD.\n\n"
    "return [\n" + "\n".join(lines) + "\n];\n"
)
(ROOT / "src/php/montefiskal-core/src/Text/nfd-ascii.php").write_text(out, encoding="utf-8")
