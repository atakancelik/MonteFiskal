#!/usr/bin/env python3
"""Generates docs/ai/context.md and docs/ai/troubleshooting.md (ai-assistant-kit.md section 9, item 2).

Usage: python3 -I tools/ai-kit/generate.py
The ai-kit CI job runs it and fails when the committed files differ.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, error_codes, rules, version  # noqa: E402

HERE = Path(__file__).resolve().parent


def context() -> str:
    src = (HERE / "context.src.md").read_text(encoding="utf-8")
    rb = rules()

    def rule(m: re.Match) -> str:
        rid = m.group(1)
        if rid not in rb:
            raise SystemExit(f"unknown rule {rid} in context.src.md")
        return f"> **{rid}**: {rb[rid]}"

    def ruleid(m: re.Match) -> str:
        if m.group(1) not in rb:
            raise SystemExit(f"unknown rule {m.group(1)} in context.src.md")
        return m.group(1)

    def sample(m: re.Match) -> str:
        path, lang = m.group(1), m.group(2)
        code = (ROOT / path).read_text(encoding="utf-8").rstrip("\n")
        return f"<!-- sample: {path} -->\n```{lang}\n{code}\n```"

    out = src.replace("{{version}}", version())
    out = re.sub(r"\{\{rule:(BR-[A-Z]+\d+)\}\}", rule, out)
    out = re.sub(r"\{\{ruleid:(BR-[A-Z]+\d+)\}\}", ruleid, out)
    out = re.sub(r"\{\{sample:([^:}]+):([a-z]+)\}\}", sample, out)
    return out


def troubleshooting() -> str:
    lines = [
        "# Error codes: what they mean and what to do",
        "",
        f"> Version {version()}. Generated by `tools/ai-kit/generate.py` from `data/error-codes.json`; do not edit by hand.",
        "",
        "Before showing a request or response to anyone, redact the TIN, names, certificate and signature values.",
        "\"Retry\" means the same request may be resent unchanged (same IKOF, subsequent-delivery flag set). \"Retry after fix\"",
        "means the cause must be fixed first; a fiscalized invoice is then corrected, never re-issued with a new number.",
        "",
        "| Code | Meaning | Retry | Retry after fix | Likely cause | What to do | Ask the developer |",
        "|---|---|---|---|---|---|---|",
    ]
    ask = {
        "certificate": "Which certificate is configured, is it issued to the seller's PIB, and is it expired?",
        "registration": "Which codes are configured, and do they match what the SEP shows?",
        "business": "Which order or input produced this invoice, and what did the library's validation report?",
        "cashDeposit": "Was the day's INITIAL deposit registered, and for which TCR?",
        "clock": "Is the server clock synchronised (NTP), and which time zone is configured?",
        "malformed": "Which library version produced the request, and was the XML changed after signing?",
        "schema": "Which library version produced the request, and was the XML changed after signing?",
        "signature": "Was the XML changed after signing, and does the certificate match the issuer?",
        "tcr": "Which TCR code is configured, and is it registered and active in the SEP?",
        "server": "Did it recover on its own after a few minutes?",
    }
    for c in error_codes():
        cell = lambda s: str(s or "").replace("|", "\\|").replace("\n", " ")  # noqa: E731
        lines.append(
            f"| {c['code'] if 'code' in c else '%d-%d' % tuple(c['range'])} | {cell(c.get('textEn'))} | {'yes' if c.get('retryable') else 'no'} | "
            f"{'yes' if c.get('retryAfterFix') else 'no'} | {cell(c.get('cause'))} | {cell(c.get('action'))} | "
            f"{cell(ask.get(c.get('class', ''), 'What changed since the last accepted invoice?'))} |"
        )
    lines += ["", "Codes not in this table: treat as not retryable, keep the request, and open a `spec-change` issue.", ""]
    return "\n".join(lines)


STAMP = re.compile(r"\b(Targets|integrate) MonteFiskal \d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?")


def stamp_versions() -> int:
    """Each prompt names the version it targets (kit principle 6); the stamp follows Directory.Build.props."""
    changed = 0
    for path in sorted((ROOT / "docs/ai").rglob("*.md")):
        text = path.read_text(encoding="utf-8")
        new = STAMP.sub(lambda m: f"{m.group(1)} MonteFiskal {version()}", text)
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed += 1
    return changed


def main() -> int:
    out = ROOT / "docs/ai"
    out.mkdir(parents=True, exist_ok=True)
    (out / "context.md").write_text(context(), encoding="utf-8")
    (out / "troubleshooting.md").write_text(troubleshooting(), encoding="utf-8")
    stamped = stamp_versions()
    print("docs/ai/context.md, docs/ai/troubleshooting.md" + (f", version stamp in {stamped} files" if stamped else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
